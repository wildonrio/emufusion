    private static void unmatchedFractionalSourcePreservesDirectEndpoints() {
        AdaptiveFrameRateController value =
                new AdaptiveFrameRateController(120.0);
        value.setAuthoritativeSourceHz(59.94);
        value.onProducerFrame(1_000_000_000L, 1L);
        value.resetPresentation();

        long panelPeriod = Math.round(1_000_000_000.0 / 120.0);
        long sourcePeriod = Math.round(1_000_000_000.0 / 59.94);
        long display = 68_000_000_000L;
        long firstTimestamp = display - sourcePeriod;
        java.util.ArrayDeque<long[]> endpoints = new java.util.ArrayDeque<>();
        endpoints.addLast(new long[] {1L, firstTimestamp});
        endpoints.addLast(new long[] {2L, firstTimestamp + sourcePeriod});
        long nextSequence = 3L;
        long nextSource = firstTimestamp + 2L * sourcePeriod;
        int total = 0;
        int synthetic = 0;
        int real = 0;
        int advances = 0;
        int previousTick = -1;
        int minimumGap = Integer.MAX_VALUE;
        int maximumGap = 0;
        // The controller may present the exact endpoint instead of a
        // fractional sample only when the slot lands within its quarter-scan
        // advance tolerance before that endpoint (see the pair-rotation
        // look-ahead in selectBufferedPresentation).
        long advanceToleranceNs = Math.max(1_000L, panelPeriod / 4L);
        long anchorDisplay = 0L;
        long anchorSource = 0L;
        for (int tick = 0; tick < 7200; ++tick) {
            while (nextSource <= display) {
                endpoints.addLast(new long[] {nextSequence++, nextSource});
                nextSource += sourcePeriod;
            }
            long[][] pair = endpoints.toArray(new long[0][]);
            long left = pair.length > 0 ? pair[0][0] : 0L;
            long leftTs = pair.length > 0 ? pair[0][1] : 0L;
            long right = pair.length > 1 ? pair[1][0] : 0L;
            long rightTs = pair.length > 1 ? pair[1][1] : 0L;
            int decision = value.selectBufferedPresentation(display,
                    left, leftTs, right, rightTs, right > left);
            if (decision != AdaptiveFrameRateController.PRESENT_NONE) {
                if (previousTick >= 0) {
                    int gap = tick - previousTick;
                    minimumGap = Math.min(minimumGap, gap);
                    maximumGap = Math.max(maximumGap, gap);
                }
                previousTick = tick;
                if (decision == AdaptiveFrameRateController.PRESENT_SYNTHETIC) {
                    ++synthetic;
                } else {
                    ++real;
                    long selectedSourceNs = value.bufferedSelectedTargetSourceNs();
                    // Symmetric endpoint snap (2026-09-01): a REAL is always
                    // an exact retained endpoint timestamp, reached from at
                    // most a quarter scan on either side; the committed REAL
                    // then re-anchors the timeline so drift never accumulates.
                    check(selectedSourceNs == leftTs || selectedSourceNs == rightTs,
                            "59.94-to-120 REAL is an exact endpoint: selected=" +
                                    selectedSourceNs + " left=" + leftTs +
                                    " right=" + rightTs);
                    // This feed publishes each endpoint only at its own
                    // timestamp, so every REAL here is a lone left endpoint
                    // (no successor retained) and never re-anchors; the
                    // snap alone decides REAL versus interior sample.
                    anchorDisplay = display;
                    anchorSource = selectedSourceNs;
                }
                int advance = value.bufferedEndpointAdvanceAfterPresentation();
                value.commitBufferedPresentation(true);
                for (int pop = 0; pop < advance; ++pop)
                    endpoints.removeFirst();
                advances += advance;
                ++total;
            }
            display += panelPeriod;
        }
        check(Math.abs(total - Math.round(59.94 * 60.0)) <= 1,
                "unmatched 59.94 remains Direct and presents every available endpoint");
        eq(0, synthetic, "unmatched clocks never generate arbitrary phases");
        check(!value.uniformOutputQualified(), "irregular Direct holds are not claimed uniform");
        // With re-anchoring at every committed REAL and the symmetric
        // quarter-scan snap, a 59.94 source on a 120.000 panel presents each
        // real frame exactly once (the 16.7-us interval residue is always
        // inside the snap) and interpolates the alternate scan.
        // The symmetric half-output-period snap shows every endpoint on
        // its nearest scan exactly once; the alternate scan is interpolated.
        check(Math.abs(real - advances) <= 2,
                "each 59.94 interval presents exactly one REAL: real=" + real +
                        " intervals=" + advances);
        eq(total, real + synthetic, "every slot is REAL or interpolated");
        eq(2, minimumGap, "unmatched Direct has ordinary two-scan holds");
        eq(3, maximumGap, "unmatched Direct honestly exposes the periodic third-scan hold");
        eq(0, (int) value.bufferedUnderrunCount(),
                "59.94-to-120 has no scheduler underrun");
    }

