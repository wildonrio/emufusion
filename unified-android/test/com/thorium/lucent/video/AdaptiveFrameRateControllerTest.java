    private static void generationFailurePreservesProducerOwnedSourceTier() {
        AdaptiveFrameRateController controller = new AdaptiveFrameRateController(120.0);
        long now = 1_000_000_000L;
        for (int index = 0; index < 240; ++index) {
            controller.onProducerFrame(now, index + 1L);
            now += 16_666_667L;
        }
        check(controller.lockedSourceFps() == 60,
                "the producer fixture must acquire the 60-Hz source tier");
        // Renderer/submission starvation is intentionally not injected into
        // the source clock. Disabling generation must retain 60 rather than
        // deriving a fictitious 50/40 tier from presentation readiness.
        controller.setGenerationAvailable(false);
        check(controller.lockedSourceFps() == 60,
                "generation failure must preserve the producer-owned tier");
        check(controller.outputFps() == 60,
                "direct fallback must present the measured source rate");
    }

