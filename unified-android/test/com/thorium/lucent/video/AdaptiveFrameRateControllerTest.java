    private static void bufferedSyntheticPhaseStaysCenteredUnderClockSkew() {
        // NTSC-like source and panel clocks are not exactly commensurate.
        // Correct temporal resampling therefore permits the phase to traverse
        // the whole open interval, but every sample must equal the timestamp
        // formula for the exact adjacent retained endpoints.
        AdaptiveFrameRateController value = feed(120, 60, 240);
        value.resetPresentation();
        long panelPeriod = Math.round(1_000_000_000.0 / 120.0);
        // NTSC-style producer: 59.94 Hz timestamps in the same clock domain.
        long producerPeriod = Math.round(1_000_000_000.0 / 59.94);
        long display = 90_000_000_000L;
        long firstTimestamp = display - producerPeriod;
        java.util.ArrayDeque<long[]> endpoints = new java.util.ArrayDeque<>();
        endpoints.addLast(new long[] {1L, firstTimestamp});
        endpoints.addLast(new long[] {2L, firstTimestamp + producerPeriod});
        long nextSequence = 3L;
        long nextSource = firstTimestamp + 2L * producerPeriod;
        int synthetic = 0;
        int centred = 0;
        float minPhase = 1f;
        float maxPhase = 0f;
        // Sixty seconds: 7200 exact panel callbacks against 59.94-Hz stamps.
        for (int tick = 0; tick < 7200; ++tick) {
            while (nextSource <= display) {
                endpoints.addLast(new long[] {nextSequence++, nextSource});
                nextSource += producerPeriod;
            }
            long[][] pair = endpoints.toArray(new long[0][]);
            long left = pair.length > 0 ? pair[0][0] : 0L;
            long leftTs = pair.length > 0 ? pair[0][1] : 0L;
            long right = pair.length > 1 ? pair[1][0] : 0L;
            long rightTs = pair.length > 1 ? pair[1][1] : 0L;
            int decision = value.selectBufferedPresentation(
                    display, left, leftTs, right, rightTs, right > left);
            if (decision != AdaptiveFrameRateController.PRESENT_NONE) {
                int advance = value.bufferedEndpointAdvanceAfterPresentation();
                if (decision == AdaptiveFrameRateController.PRESENT_SYNTHETIC
                        && tick > 240) {
                    float phase = value.bufferedSelectedPhase();
                    double expected = (double)
                            (value.bufferedSelectedTargetSourceNs() - leftTs) /
                            (double) (rightTs - leftTs);
                    // Lattice snap (2026-09-02): the two REALs of this pair are
                    // shown on scans exactly two apart, so the interior scan
                    // is their temporal midpoint and the content phase is
                    // exactly 0.5 -- "centered", as the test's name says.
                    // Following the drifting stamp fraction instead put the
                    // content off-centre relative to the shown frames
                    // (measured 0.44/0.77 on a paced 40->120 stretch).
                    double scans = (double) (rightTs - leftTs) / panelPeriod;
                    long n = Math.round(scans);
                    if (n >= 2L && Math.abs(scans - n) <= 0.05 * n) {
                        long k = Math.round(expected * n);
                        if (k >= 1L && k <= n - 1L) expected = (double) k / (double) n;
                    }
                    near(expected, phase, 0.00001,
                            "synthetic phase is centred on the output lattice");
                    ++synthetic;
                    if (Math.abs(phase - 0.5f) < 1.0e-4f) ++centred;
                    minPhase = Math.min(minPhase, phase);
                    maxPhase = Math.max(maxPhase, phase);
                }
                value.commitBufferedPresentation(true);
                for (int pop = 0; pop < advance; ++pop)
                    endpoints.removeFirst();
            }
            display += panelPeriod;
        }
        check(synthetic > 3000,
                "skewed 59.94-source run selects a full synthetic stream: " +
                        synthetic);
        // The post-swap owner now rotates when the next physically predicted
        // slot reaches the right endpoint. That correctly removes redundant
        // near-right samples while every retained phase above still equals the
        // exact adjacent-timestamp fraction.
        // Symmetric half-scan endpoint snap (2026-09-01): a sample within
        // half a scan (0.25 of this 16.68-ms period) of either endpoint is
        // that endpoint, so interior phases span exactly the open window
        // outside the snap and nothing else.
        // Lattice snap (2026-09-02): every interior scan between two REALs
        // shown two scans apart is their temporal midpoint, so phases are
        // exactly 0.5 apart from the quarter-scan edge cases the endpoint
        // snap leaves interior (0.25 / 0.75), which stay on the timestamp
        // formula because they round to an endpoint index.
        check(minPhase >= 0.24f && maxPhase <= 0.76f,
                "phases stay inside the open window: [" + minPhase + ", " + maxPhase + "]");
        check(centred * 10 >= synthetic * 9,
                "at least ninety percent of skewed 59.94 synthetics are centred: " +
                        centred + "/" + synthetic);
    }

