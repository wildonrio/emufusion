    private static void exactGeneratedGapAtEveryTier() {
        int[] tiers = {20, 30, 40, 60};
        int[] factors = {3, 2, 3, 2};
        for (int index = 0; index < tiers.length; ++index) {
            int source = tiers[index];
            int factor = factors[index];
            AdaptiveFrameRateController value = new AdaptiveFrameRateController(120);
            long sourcePeriod = Math.round(1_000_000_000.0 / source);
            long displayPeriod = Math.round(1_000_000_000.0 / 120.0);
            long nextSource = 1_000_000_000L;
            // Establish the requested tier and give the presentation scheduler
            // a full steady-state interval before measuring it.
            for (int frame = 0; frame < 240; ++frame) {
                value.onProducerFrame(nextSource);
                nextSource += sourcePeriod;
            }
            eq(source, value.lockedSourceFps(), "locked tier before cadence proof");
            value.resetPresentation();
            long display = nextSource;
            int promotedImages = 0;
            int generated = 0;
            int promoted = 0;
            int submitted = 0;
            for (int panelFrame = 0; panelFrame < 600; ++panelFrame) {
                while (nextSource <= display) {
                    value.onProducerFrame(nextSource);
                    nextSource += sourcePeriod;
                }
                if (value.presentationDue(display)) {
                    boolean didPromote = value.promoteIfDue(display);
                    if (didPromote) ++promotedImages;
                    float phase = value.interpolation(display, promotedImages);
                    // Measure the final two seconds, after three seconds of cadence
                    // warm-up. This matches a health window, not startup transients.
                    if (panelFrame >= 360) {
                        ++submitted;
                        if (didPromote) ++promoted;
                        if (!didPromote && phase > 0f && phase < 1f) ++generated;
                    }
                }
                display += displayPeriod;
            }
            eq(source * 2, promoted, source + " FPS real presents over two seconds");
            eq(source * 2 * (factor - 1), generated,
                    source + " FPS generated presents over two seconds");
            eq(source * 2 * factor, promoted + generated,
                    source + " FPS real plus generated is exact x" + factor +
                            " output");
            eq(submitted, promoted + generated,
                    source + " FPS has no unclassified duplicate swaps");
            check(generated <= promoted * (factor - 1),
                    source + " FPS generates at most " + (factor - 1) +
                            " frames per real frame");
        }
    }

