    private static BufferedCounts runReadyBufferedSchedule(
            AdaptiveFrameRateController value, int panel, int panelTicks) {
        value.resetPresentation();
        long period = Math.round(1_000_000_000.0 / panel);
        long display = 70_000_000_000L;
        long left = 1L;
        long right = 2L;
        long next = 3L;
        int previousSelectedTick = -1;
        BufferedCounts counts = new BufferedCounts();
        counts.minimumTickGap = Integer.MAX_VALUE;
        for (int tick = 0; tick < panelTicks; ++tick) {
            int decision = value.selectBufferedPresentation(
                    display, left, right, true);
            if (decision != AdaptiveFrameRateController.PRESENT_NONE) {
                if (previousSelectedTick >= 0) {
                    int gap = tick - previousSelectedTick;
                    counts.minimumTickGap = Math.min(counts.minimumTickGap, gap);
                    counts.maximumTickGap = Math.max(counts.maximumTickGap, gap);
                }
                previousSelectedTick = tick;
                if (decision == AdaptiveFrameRateController.PRESENT_REAL) {
                    float phase = value.bufferedSelectedPhase();
                    check(phase == 0f || phase == 1f,
                            "buffered REAL renders one exact retained endpoint");
                    ++counts.real;
                } else {
                    check(value.bufferedSelectedPhase() > 0f &&
                                    value.bufferedSelectedPhase() < 1f,
                            "buffered SYNTHETIC is strictly between endpoints");
                    ++counts.synthetic;
                }
                int advance = value.bufferedEndpointAdvanceAfterPresentation();
                value.commitBufferedPresentation(true);
                if (advance == 1) {
                    left = right;
                    right = next++;
                    ++counts.endpointAdvances;
                }
                ++counts.total;
            }
            display += period;
        }
        if (counts.minimumTickGap == Integer.MAX_VALUE) counts.minimumTickGap = 0;
        return counts;
    }

