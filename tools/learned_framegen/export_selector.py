"""Export a trained visibility selector (selector.py) as GLSL ES 3.00 passes.

usage: python3 -m tools.learned_framegen.export_selector CHECKPOINT OUT.java

Passes (DenseInverseSearchFlow.estimateSelection / bindGenerateSelect):
  SELECT_FEATURES  field grid, 2 RGBA16F targets: uGrayA, uGrayC (the DIS luma
                   pyramid at the field's level), uPhaseFlow, uSize
  SELECT_C1..C3    field grid, 4 RGBA8 targets each (export_gles conventions)
  SELECT_OUT       field grid, 1 RGBA16F target: the four logits
  SELECT_GENERATE  full size (VERTEX_QUAD): softmax(logits) over A warped back,
                   C warped forward, A and C; then production's structure-mask
                   and cut/fade overrides, as GENERATE_PHASE applies them
The features pass and the blend work in native GL coordinates (row 0 at the
bottom, field vectors y up) and write the vertical motion negated, which is
the top-down convention the network was trained in; the convolutions use
export_gles's top-origin addressing.
"""
import argparse
from pathlib import Path

import torch

from . import dis_gles as D
from .export_gles import HEADER, HELPERS, conv_shader, java_string
from .selector import MOTION_SCALE, Selector

FEATURES = (HEADER +
    "uniform sampler2D uGrayA,uGrayC,uPhaseFlow;uniform ivec2 uSize;\n"
    "layout(location=0) out vec4 o0;layout(location=1) out vec4 o1;\n"
    "void main(){ivec2 p=ivec2(gl_FragCoord.xy);vec2 s=vec2(uSize);\n"
    " vec2 v=texelFetch(uPhaseFlow,p,0).xy;vec2 x=vec2(p)+0.5;\n"
    " float wa=texture(uGrayA,(x-0.5*v)/s).r,wc=texture(uGrayC,(x+0.5*v)/s).r;\n"
    " float ga=texelFetch(uGrayA,p,0).r,gc=texelFetch(uGrayC,p,0).r;\n"
    " o0=vec4(wa,wc,ga,gc);\n"
    f" o1=vec4(abs(wa-wc),abs(ga-gc),v.x*{MOTION_SCALE!r},-v.y*{MOTION_SCALE!r});}}\n")

GENERATE = (HEADER +
    "uniform sampler2D uFrameA,uFrameC,uPhaseFlow,uLogits;uniform float uT;uniform vec2 uFlowSize;\n"
    "in vec2 vTexCoord;layout(location=0) out vec4 o0;\n"
    "uniform sampler2D uStructureMask;uniform float uStructure,uStructureMinMotionPx;uniform vec2 uHistorySize;\n"
    "uniform sampler2D uCut;uniform float uCutEnabled;\n"
    "void main(){vec2 u=vTexCoord;vec2 v=texture(uPhaseFlow,u).xy/uFlowSize;\n"
    " vec3 aw=texture(uFrameA,u-uT*v).rgb,cw=texture(uFrameC,u+(1.0-uT)*v).rgb;\n"
    " vec3 a0=texture(uFrameA,u).rgb,c0=texture(uFrameC,u).rgb;\n"
    " vec4 l=texture(uLogits,u);vec4 e=exp(l-vec4(max(max(l.x,l.y),max(l.z,l.w))));e/=dot(e,vec4(1.0));\n"
    " vec3 w=e.x*aw+e.y*cw+e.z*a0+e.w*c0;\n"
    " if(uStructure>0.5&&length(v*uHistorySize)>=uStructureMinMotionPx){\n"
    "  w=mix(w,(1.0-uT)*a0+uT*c0,texture(uStructureMask,u).r);}\n"
    " vec4 ct=texture(uCut,vec2(0.5));\n"
    f" w=mix(mix(w,a0,uCutEnabled*step({D.CUT_THRESHOLD},ct.r)),(1.0-uT)*a0+uT*c0,uCutEnabled*step(0.5,ct.g));\n"
    " o0=vec4(w,1.0);}\n")


def sources(model):
    return {
        'SELECT_FEATURES': FEATURES,
        'SELECT_C1': conv_shader(model.c1, 2, 4),
        'SELECT_C2': conv_shader(model.c2, 4, 4),
        'SELECT_C3': conv_shader(model.c3, 4, 4),
        'SELECT_OUT': conv_shader(model.out, 4, 1),
        'SELECT_GENERATE': GENERATE,
    }


def java_class(shaders, checkpoint):
    body = "".join(f"    static final String {name} = {java_string(text)};\n\n"
                   for name, text in shaders.items())
    return ("package com.thorium.preview.game;\n\n"
            "/**\n"
            " * Generated by tools/learned_framegen/export_selector.py from " + checkpoint + ";\n"
            " * do not edit. The learned visibility selector over synthesis 24's DIS\n"
            " * field (our own network and weights, trained on our own captures).\n"
            " */\n"
            "final class LearnedSelectorShaders {\n"
            "    private LearnedSelectorShaders() {}\n\n" + body + "}\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('checkpoint')
    parser.add_argument('out')
    args = parser.parse_args()
    model = Selector()
    model.load_state_dict(torch.load(args.checkpoint, map_location='cpu')['model'])
    Path(args.out).write_text(java_class(sources(model), Path(args.checkpoint).name))


if __name__ == '__main__':
    main()
