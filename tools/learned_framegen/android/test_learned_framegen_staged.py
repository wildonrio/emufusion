"""The learned estimator's generated shaders and its Java runtime agree.

LearnedFrameShaders.java is generated by tools/learned_framegen/export_gles.py
from our own trained weights (structure from the REA study of Lossless
Scaling's frame generation; none of its code, shaders or weights). These
checks need no GPU: every generated shader compiles as GLSL ES 3.00, every
uniform the runtime sets exists in the shader it binds, and synthesis 20 is
the only way in. tools/learned_framegen/verify_gles.py compares each pass
with PyTorch on a desktop GPU.
"""
import re
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GAME = ROOT / "unified-android" / "src" / "com" / "thorium" / "preview" / "game"
SHADERS = GAME / "LearnedFrameShaders.java"
ESTIMATOR = GAME / "LearnedFrameEstimator.java"
GENERATOR = GAME / "DisplayFrameGenerator.java"
SWITCH = GAME / "TimelineSchedulerSwitch.java"
GLSLANG = shutil.which("glslangValidator") or "/opt/homebrew/bin/glslangValidator"


def generated_shaders():
    source = SHADERS.read_text()
    found = {}
    for match in re.finditer(r'static final String (\w+) = new StringBuilder\(\d+\)\n((?:\s+\.append\(".*"\)\n)+)', source):
        parts = re.findall(r'\.append\("(.*)"\)', match.group(2))
        text = "".join(bytes(p, "utf-8").decode("unicode_escape") for p in parts)
        found[match.group(1)] = text
    return found


class LearnedShaderTest(unittest.TestCase):
    def test_every_shader_the_runtime_links_is_generated(self):
        shaders = generated_shaders()
        used = set(re.findall(r"LearnedFrameShaders\.(\w+)", ESTIMATOR.read_text()))
        self.assertTrue(used)
        self.assertEqual(used - set(shaders), set())

    @unittest.skipUnless(Path(GLSLANG).exists(), "glslangValidator not installed")
    def test_every_generated_shader_compiles_as_gles3(self):
        with tempfile.TemporaryDirectory(prefix="learned-shaders-") as temporary:
            for name, text in generated_shaders().items():
                self.assertTrue(text.startswith("#version 300 es\n"), name)
                path = Path(temporary, name + (".vert" if name.startswith("VERTEX") else ".frag"))
                path.write_text(text)
                result = subprocess.run([GLSLANG, str(path)], capture_output=True, text=True, timeout=60)
                with self.subTest(shader=name):
                    self.assertEqual(result.returncode, 0, result.stdout[-2000:])

    def test_runtime_uniforms_exist_in_their_shaders(self):
        shaders = generated_shaders()
        uniforms = {name: set(re.findall(r"uniform \w+ ([\w,]+);", text)) for name, text in shaders.items()}
        declared = {name: {u for group in groups for u in group.split(",")} for name, groups in uniforms.items()}
        expect = {
            "CORR": {"uA0", "uA3", "uB0", "uB3", "uCoarse", "uHasCoarse", "uT", "uOut"},
            "H1OUT": {"uIn0", "uIn3", "uCoarse", "uHasCoarse", "uIn", "uOut"},
            "H2OUT": {"uIn0", "uIn3", "uCoarse", "uHasCoarse", "uIn", "uOut"},
            "VIS0": {"uA0", "uB3", "uLow1", "uLow2", "uT", "uOut"},
            "VISOUT": {"uIn0", "uIn1", "uPrev", "uHasPrev", "uIn", "uOut"},
            "ENC0": {"uIn0", "uIn", "uOut"},
            "H1C1": {"uIn0", "uIn1", "uIn2", "uIn", "uOut"},
            "GENERATE": {"uFrameA", "uFrameB", "uF1", "uF2", "uW", "uT", "uQ0"},
        }
        for name, names in expect.items():
            with self.subTest(shader=name):
                self.assertEqual(names - declared[name], set())

    def test_activations_are_rgba8_and_fields_half_float(self):
        estimator = ESTIMATOR.read_text()
        # Fields and logits are RGBA16F; every hidden tensor is RGBA8 (the
        # network's clip-and-quantise activation).
        self.assertIn("field1[k] = texture(qw, qh, true);", estimator)
        self.assertIn("logits[k] = texture(qw, qh, true);", estimator)
        self.assertIn("features[s][k][i] = texture(qw, qh, false);", estimator)
        # ES 3.0 draws the intersection of all attachments: stale ones are detached.
        self.assertIn("for (int i = targets.length; i < attached; ++i)", estimator)


class LearnedSelectionTest(unittest.TestCase):
    def test_synthesis_twenty_selects_the_learned_path(self):
        switch = SWITCH.read_text()
        generator = GENERATOR.read_text()
        self.assertIn("static final int LEARNED_SYNTHESIS_LEVEL = 20;", switch)
        self.assertIn("synthesisLevel = level == LEARNED_SYNTHESIS_LEVEL ? level : Math.max(0, Math.min(15, level));", switch)
        self.assertIn("if (ids[i] == LEARNED_SYNTHESIS_LEVEL) continue;", switch)
        self.assertIn("if (synthesisLevel == TimelineSchedulerSwitch.LEARNED_SYNTHESIS_LEVEL &&\n"
                      "                drawLearnedFrame(phase)) return;", generator)
        self.assertIn("if (learnedEstimator != null) learnedEstimator.release();", generator)


if __name__ == "__main__":
    unittest.main()
