"""GPU dense inverse search (synthesis 21): generated shaders and Java runtime agree.

DenseInverseSearchShaders.java is generated by tools/learned_framegen/dis_gles.py
(Kroeger et al., ECCV 2016, our own implementation); dis_eval.py runs the same
passes on a desktop GPU over captured hold-out triplets. These checks need no
GPU: the generated class matches the generator, every shader compiles as GLSL
ES 3.00, every uniform the runtime sets exists, and synthesis 21 is the way in.
"""
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GAME = ROOT / "unified-android" / "src" / "com" / "thorium" / "preview" / "game"
SHADERS = GAME / "DenseInverseSearchShaders.java"
RUNTIME = GAME / "DenseInverseSearchFlow.java"
GENERATOR = GAME / "DisplayFrameGenerator.java"
SWITCH = GAME / "TimelineSchedulerSwitch.java"
GLSLANG = shutil.which("glslangValidator") or "/opt/homebrew/bin/glslangValidator"
sys.path.insert(0, str(ROOT))
from tools.learned_framegen import dis_gles  # noqa: E402


class DisShaderTest(unittest.TestCase):
    def test_generated_class_matches_the_generator(self):
        self.assertEqual(SHADERS.read_text(), dis_gles.java_source())

    @unittest.skipUnless(Path(GLSLANG).exists(), "glslangValidator not installed")
    def test_every_shader_compiles_as_gles3(self):
        with tempfile.TemporaryDirectory(prefix="dis-shaders-") as temporary:
            for name, text in dis_gles.shaders().items():
                path = Path(temporary, name + (".vert" if name.startswith("VERTEX") else ".frag"))
                path.write_text(text)
                result = subprocess.run([GLSLANG, str(path)], capture_output=True, text=True, timeout=60)
                with self.subTest(shader=name):
                    self.assertEqual(result.returncode, 0, result.stdout[-2000:])

    def test_runtime_uniforms_exist_in_their_shaders(self):
        shaders = dis_gles.shaders()
        runtime = RUNTIME.read_text()
        program_of = {"gray": "GRAY", "down": "DOWN", "grad": "GRAD", "patchSearch": "PATCH_SEARCH",
                      "densify": "DENSIFY", "generate": "GENERATE", "toRaw": "TO_RAW",
                      "phaseSearch": "PHASE_SEARCH", "phaseDensify": "PHASE_DENSIFY",
                      "generatePhase": "GENERATE_PHASE", "cutProgram": "CUT"}
        used = set(re.findall(r'(?:bind|location)\((\w+), "(\w+)"', runtime))
        self.assertTrue(used)
        for program, name in used:
            with self.subTest(program=program, uniform=name):
                self.assertRegex(shaders[program_of[program]], r"uniform [^;]*\b" + name + r"\b")

    def test_method_shape(self):
        search = dis_gles.shaders()["PATCH_SEARCH"]
        # 8x8 patches on a 3-px grid, 6 inverse-compositional iterations
        # (as good as 12 on the captured hold-out set, half the cost),
        # mean-normalised, keeping the start when the search got worse.
        self.assertEqual((dis_gles.PATCH, dis_gles.STRIDE, dis_gles.ITERATIONS), (8, 3, 6))
        runtime = RUNTIME.read_text()
        self.assertIn(f"static final int PATCH = {dis_gles.PATCH};", runtime)
        self.assertIn(f"static final int STRIDE = {dis_gles.STRIDE};", runtime)
        # Two fixed-point steps: motion sampled where the content comes from.
        self.assertEqual(dis_gles.GENERATE.count("p=u-uT*fac(p);"), 2)
        self.assertIn("u-=hi*b;", search)
        self.assertIn("if(e1>e0||any(isnan(u))){u=u0;e1=e0;}", search)
        # Coarsest level: whole-pixel starts within 2 px, zero motion favoured.
        self.assertIn("for(int dy=-2;dy<=2;++dy)for(int dx=-2;dx<=2;++dx)", search)
        self.assertIn("best=0.8*(aa-a*a/N+(stt-st*st/N)-2.0*(at-a*st/N));", search)
        self.assertIn("float w=1.0/max(1.0,d);", dis_gles.shaders()["DENSIFY"])


class SingleRouteTest(unittest.TestCase):
    def test_every_source_renders_the_same_route(self):
        # Like LSFG, nothing about the system picks the motion route (3.2.80).
        host = (GAME / "InWindowGameHost.java").read_text()
        surface = (GAME / "GameSurfaceView.java").read_text()
        generator = GENERATOR.read_text()
        for text in (host, surface, generator, (GAME / "FrameGenerationRenderer.java").read_text()):
            self.assertNotIn("PerPhaseMotionPreferred", text)
            self.assertNotIn("PER_PHASE_MOTION_SYSTEMS", text)
        self.assertIn("(disDefault && !holdoutRendering);", generator)
        self.assertIn("        return disMotionNormal;\n", generator)
        # Motion under one source pixel is taken as zero.
        self.assertIn(" if(length(v*uHistorySize)<1.0)w=(1.0-uT)*a0+uT*c0;else\n", dis_gles.shaders()["GENERATE_PHASE"])


