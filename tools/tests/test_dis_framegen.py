class WorkAdaptationTest(unittest.TestCase):
    def test_lone_deadline_misses_do_not_shed_work(self):
        policy = (ROOT / "unified-android" / "src" / "com" / "thorium" / "emufusion" / "video" /
                  "GpuWorkAdaptationPolicy.java").read_text()
        self.assertIn("public static final int ISOLATED_MISS_PAIRS = 600;", policy)
        self.assertIn("if (stepsNeedBlocks() && isolatedMiss && workLevel < maxWorkLevel - 1)\n"
                      "                return Decision.UNCHANGED;", policy)
        test = (ROOT / "unified-android" / "test" / "com" / "thorium" / "emufusion" / "video" /
                "GpuWorkAdaptationPolicyTest.java").read_text()
        self.assertIn("loneDeadlineMissesDoNotRatchetWork();", test)
        self.assertIn("stallEventsMinutesApartKeepWork();", test)
        self.assertIn("public static final int MISS_EVENT_PAIRS = 60;", policy)
        # Unknown physical headroom (nearly every Thor pair) leaves recovery to
        # shader time; only a marginal pair spends the credit.
        generator = GENERATOR.read_text()
        self.assertIn("if (!verified && result.outcome == GpuPhysicalHeadroomLedger.Outcome.MARGINAL_HEADROOM)\n"
                      "                denseGpuAdaptation.invalidateRecoveryEvidence();", generator)
        self.assertNotIn("if (!verified) denseGpuAdaptation.invalidateRecoveryEvidence();", generator)
        # A real frame on the wrong slot is engine pacing: counted, never shed.
        self.assertIn("                else\n                    ++denseGpuEndpointDeadlineMisses;", generator)
        self.assertNotIn('shedDenseWork("physical-pair-deadline-miss");', generator)


class DisSelectionTest(unittest.TestCase):
    def test_synthesis_twenty_one_selects_dis(self):
        switch = SWITCH.read_text()
        generator = GENERATOR.read_text()
        self.assertIn("static final int DIS_SYNTHESIS_LEVEL = 21;", switch)
        self.assertIn("if (ids[i] == DIS_SYNTHESIS_LEVEL || ids[i] == DIS_MOTION_SYNTHESIS_LEVEL ||\n"
                      "                        ids[i] == DIS_PHASE_SYNTHESIS_LEVEL) continue;", switch)
        self.assertIn("boolean dis = disPhase || synthesisLevel == TimelineSchedulerSwitch.DIS_SYNTHESIS_LEVEL;", generator)
        self.assertIn("if (dis && drawDisFrame(phase, disPhase)) return;", generator)
        # Synthesis 24 applies synthesis 15's static-structure mask.
        self.assertIn("boolean structure = structureMaskProgram != 0 && renderStructureMask();", generator)
        self.assertIn("w=mix(w,(1.0-uT)*a0+uT*c0,texture(uStructureMask,u).r);", dis_gles.shaders()["GENERATE_PHASE"])
        # 3.2.78: the cut/fade verdict taken after DIS (a camera turn is not a
        # cut), per-pixel zero-motion selection and the sharper densifications.
        self.assertIn("w=mix(mix(w,a0,uCutEnabled*step(0.6,ct.r)),(1.0-uT)*a0+uT*c0,uCutEnabled*step(0.5,ct.g));",
                      dis_gles.shaders()["GENERATE_PHASE"])
        self.assertIn("if(e0+8.0/255.0<eM)w=(1.0-uT)*a0+uT*c0;", dis_gles.shaders()["GENERATE_PHASE"])
        self.assertIn("structure ? structureMaskTexture : 0, 2f * structureStepPixels(), flow.cutTexture());", generator)
        self.assertIn("if (perPhase && disPhaseFlow == null) disPhaseFlow = new DenseInverseSearchFlow(true);", generator)
        self.assertIn("boolean disCut = maxFragmentTextureUnits >= 9 && disMotionUsable();", generator)
        self.assertIn("disCut ? disFlow.cutTexture() :", generator)
        shaders = dis_gles.shaders()
        self.assertIn("float m=max(1.0,d);float w=1.0/(m*m);", shaders["PHASE_DENSIFY"])
        self.assertIn("float m=max(1.0,d);float w=1.0/(m*m);", shaders["DENSIFY_SHARP"])
        self.assertIn("n1+=step(0.12,abs(texture(uGrayC,q).r-a));", shaders["CUT"])
        self.assertIn("o0=vec4(min(n0,n1)/n,fade,0.0,1.0);", shaders["CUT"])
        # Two flat frames that differ are a fade, not a cut.
        self.assertIn(" else fade=step(n*sbb-sb*sb,n*n*0.0009)*step(0.015,d/n);", shaders["CUT"])
        runtime = RUNTIME.read_text()
        self.assertIn("densify = link(v, sharp ? DenseInverseSearchShaders.DENSIFY_SHARP : DenseInverseSearchShaders.DENSIFY);",
                      runtime)
        self.assertIn('bind(cutProgram, "uFlowAC", flows[0][used], 2);', runtime)
        # QA 24: motion refined per output phase (symmetric matching at t).
        self.assertIn("static final int DIS_PHASE_SYNTHESIS_LEVEL = 24;", switch)
        self.assertIn("flow.estimatePhase(phase);", generator)
        self.assertIn("if (disFlow != null) disFlow.release();", generator)
        # 2-D at full analysis resolution, larger sources at a half (averaged
        # onto the solver's grid anyway); one level coarser from work level 3.
        self.assertIn("int base = disSmallSource() ? 0 : 1;", generator)
        self.assertIn("return denseWorkLevel >= 3 ? base + 1 : base;", generator)
        self.assertEqual(generator.count("disFlow.estimate(disStopLevel());"), 1)
        self.assertEqual(generator.count(" flow.estimate(disStopLevel());"), 1)
        # Flows depend only on the pair, not the phase.
        self.assertIn("if (keyA != flow.estimateKeyA || keyB != flow.estimateKeyB) {", generator)

    def test_dis_motion_feeds_the_hand_written_synthesis(self):
        generator = GENERATOR.read_text()
        runtime = RUNTIME.read_text()
        self.assertIn("static final int DIS_MOTION_SYNTHESIS_LEVEL = 22;", SWITCH.read_text())
        # DIS flows go through the solver's own validation and fill.
        self.assertIn("convertDisMotion(disFlow.motionRaw, disFlow.motionValidated, disFlow.motionFill, limit);",
                      generator)
        self.assertIn("validateDenseField(raw, validated, 0, historyTextures[previousIndex], historyTextures[currentIndex]);",
                      generator)
        self.assertIn("fillDenseField(validated, fill, 1);", generator)
        self.assertIn("if (densePyramidEnabled && disMotionUsable()) return disFlow.motionValidated[0];", generator)
        # Valid only for the pair it was computed on (densePromotions advances after).
        self.assertIn("disMotionPromotion = densePromotions + 1;", generator)
        # Raw [0] is current->previous (DIS reference C), like the solver's direction 0.
        self.assertIn("int flow = flows[d == 0 ? 1 : 0][used];", runtime)
        self.assertIn("motionRaw[d] = rgba8(width, height, true);", runtime)

    def test_dis_is_the_default_outside_the_hold_out(self):
        switch = SWITCH.read_text()
        generator = GENERATOR.read_text()
        self.assertIn('DIS_GLOBAL = "emufusion_framegen_dis"', switch)
        # Every source renders synthesis 24; 22 is QA only.
        self.assertIn("boolean disPhase = synthesisLevel == TimelineSchedulerSwitch.DIS_PHASE_SYNTHESIS_LEVEL ||\n"
                      "                (disDefault && !holdoutRendering);", generator)
        self.assertIn("private boolean disSmallSource() { return historyWidth <= 400 && historyHeight <= 300; }",
                      generator)
        # In normal play DIS replaces the block matcher's search; the hold-out keeps both.
        self.assertIn("boolean disOnly = !holdoutMode &&\n"
                      "                    (disMotionForPlay() ? estimateDisMotion() : disPhaseOnly);", generator)
        # The per-phase route skips the block matcher's pyramid and global seed.
        self.assertIn("boolean disPhaseOnly = !holdoutMode && !disMotionForPlay() && disPhaseForPlayReady();", generator)
        self.assertIn("            if (!disPhaseOnly) {\n                buildDensePairPyramids();", generator)
        self.assertIn("if (!disDefault) return false;", generator)
        self.assertIn("if (!disOnly && disMotionWanted()) estimateDisMotion();", generator)
        self.assertIn("holdoutRendering = true;", generator)
        self.assertEqual(generator.count("holdoutRendering = false;"), 2)

